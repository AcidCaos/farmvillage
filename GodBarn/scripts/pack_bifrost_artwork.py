#!/usr/bin/env python3
"""Pack only audited missing artwork from God Barn's own prepared asset copies.

The request is generated by install_bifrost_barn.py --audit-artwork on Bifrost.
The reviewed base bundle is the authority for every permitted image identity;
neither the request nor the local catalog can authorize a different source file.
No game asset folders, imports, or farm data are used.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import sys
import tarfile
import tempfile


BARN_ROOT = Path(__file__).resolve().parents[1]
BUNDLE_NAME = 'god-barn-catalog-recovery.tar.gz'
EXPECTED_SHA256 = '7ff2f6a639f08f656343f5d6b465effdecdcfb3bfc4534c5545ebc4a39067f96'
IMAGE_PATH = re.compile(r'static/assets/items/[0-9a-fA-F]{32,64}\.(?i:png|jpg|jpeg|gif|webp)')
SHA256 = re.compile(r'[0-9a-f]{64}')
MAX_IMAGE_BYTES = 64 * 1024 * 1024
MAX_REQUEST_BYTES = 40 * 1024 * 1024
MAX_CATALOG_BYTES = 256 * 1024 * 1024


def digest(contents):
    return hashlib.sha256(contents).hexdigest()


def progress(message):
    print('[God Barn artwork] ' + message, file=sys.stderr, flush=True)


def ordinary(path, *, directory=False):
    """Reject links at every component before opening an existing local path."""
    path = Path(path).absolute()
    for component in (path, *path.parents):
        if component.is_symlink():
            raise ValueError('Refusing symbolic link: ' + str(component))
    if not (path.is_dir() if directory else path.is_file()):
        raise ValueError('Expected ordinary ' + ('directory: ' if directory else 'file: ') + str(path))
    return path


def read_regular(path, limit):
    path = ordinary(path)
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > limit:
            raise ValueError('File is not ordinary or exceeds its byte limit: ' + str(path))
        contents = stream.read(limit + 1)
    if len(contents) > limit:
        raise ValueError('File exceeds its byte limit: ' + str(path))
    return contents


def safe_relative(value):
    if not isinstance(value, str):
        raise ValueError('Asset paths must be strings.')
    path = PurePosixPath(value)
    if (not value or path.is_absolute() or str(path) != value or
            any(part in ('', '.', '..') or part.startswith('.') for part in path.parts) or
            '\\' in value or '\n' in value or '\r' in value or '\0' in value):
        raise ValueError('Unsafe asset path: ' + repr(value))
    return value


def json_without_duplicate_keys(contents):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError('Duplicate JSON field: ' + str(key))
            result[key] = value
        return result
    return json.loads(contents, object_pairs_hook=unique)


def bundle_artwork(barn_root, expected_bundle_sha256):
    """Read selected identities from the actual checksum-verified base bundle."""
    if not isinstance(expected_bundle_sha256, str) or not SHA256.fullmatch(expected_bundle_sha256):
        raise ValueError('The reviewed bundle identity is invalid.')
    bundle = ordinary(barn_root / '.build' / BUNDLE_NAME)
    contents = read_regular(bundle, 64 * 1024 * 1024)
    if digest(contents) != expected_bundle_sha256:
        raise ValueError('The prepared base bundle does not match its reviewed SHA256.')
    required = {'GodBarn/data/catalog.json.gz', 'GodBarn/data/asset-map.json'}
    metadata = {}
    with tarfile.open(fileobj=io.BytesIO(contents), mode='r:gz') as archive:
        for member in archive:
            if member.name not in required:
                continue
            if member.name in metadata or not member.isfile() or member.size > 32 * 1024 * 1024:
                raise ValueError('Invalid or duplicate base bundle artwork metadata.')
            stream = archive.extractfile(member)
            metadata[member.name] = stream.read(member.size + 1)
            if len(metadata[member.name]) != member.size:
                raise ValueError('Incomplete base bundle artwork metadata.')
    if set(metadata) != required:
        raise ValueError('The prepared base bundle lacks artwork metadata.')
    mapping = json_without_duplicate_keys(metadata['GodBarn/data/asset-map.json'])
    with gzip.GzipFile(fileobj=io.BytesIO(metadata['GodBarn/data/catalog.json.gz'])) as stream:
        catalog_bytes = stream.read(MAX_CATALOG_BYTES + 1)
    if len(catalog_bytes) > MAX_CATALOG_BYTES:
        raise ValueError('The base bundle catalog exceeds its byte limit.')
    catalog = json_without_duplicate_keys(catalog_bytes)
    if not isinstance(mapping, dict) or not isinstance(catalog, list):
        raise ValueError('The base bundle artwork metadata has an invalid shape.')
    selected, names = {}, set()
    for row in catalog:
        if not isinstance(row, dict) or not isinstance(row.get('name'), str):
            raise ValueError('Invalid base bundle catalog record.')
        name = row['name']
        if name in names:
            continue
        names.add(name)
        artwork = row.get('artwork', {})
        if not isinstance(artwork, dict) or artwork.get('status') != 'exact':
            continue
        image = row.get('image')
        if not isinstance(image, str) or not image.startswith('/') or not IMAGE_PATH.fullmatch(image[1:]):
            raise ValueError('Unsafe selected image in the base bundle.')
        path = image[1:]
        sha256, size = artwork.get('sha256'), artwork.get('bytes')
        if (not isinstance(sha256, str) or not SHA256.fullmatch(sha256) or
                type(size) is not int or not 0 < size <= MAX_IMAGE_BYTES or path not in mapping):
            raise ValueError('Invalid selected artwork identity in the base bundle.')
        asset_path = safe_relative(mapping[path])
        expected = {'path': path, 'sha256': sha256, 'bytes': size, 'assetPath': asset_path}
        if path in selected and selected[path] != expected:
            raise ValueError('Conflicting selected artwork identities in the base bundle.')
        selected[path] = expected
    return selected


def validate_wanted(wanted, selected, expected_bundle_sha256):
    if (not isinstance(wanted, dict) or type(wanted.get('schema')) is not int or
            wanted['schema'] != 1 or wanted.get('bundleSha256') != expected_bundle_sha256 or
            not isinstance(wanted.get('items'), list)):
        raise ValueError('Artwork request is not for this reviewed base bundle.')
    if len(wanted['items']) > len(selected):
        raise ValueError('Artwork request contains more records than the reviewed catalog.')
    records, seen = [], set()
    for record in wanted['items']:
        if not isinstance(record, dict):
            raise ValueError('Invalid requested artwork record.')
        path = record.get('path')
        if not isinstance(path, str) or not IMAGE_PATH.fullmatch(path):
            raise ValueError('Unsafe requested artwork path.')
        if path in seen:
            raise ValueError('Duplicate requested artwork path: ' + path)
        seen.add(path)
        if (not isinstance(record.get('sha256'), str) or not SHA256.fullmatch(record['sha256']) or
                type(record.get('bytes')) is not int or not 0 < record['bytes'] <= MAX_IMAGE_BYTES):
            raise ValueError('Invalid requested artwork checksum or byte count.')
        safe_relative(record.get('assetPath'))
        expected = selected.get(path)
        if expected is None or any(record.get(key) != value for key, value in expected.items()):
            raise ValueError('Requested artwork differs from the reviewed catalog: ' + path)
        records.append(expected)
    return sorted(records, key=lambda record: record['path'])


def output_path(path, bundle):
    path = Path(path).absolute()
    if '..' in path.parts:
        raise ValueError('Unsafe supplement output path.')
    ordinary(path.parent, directory=True)
    if path.exists() or path.is_symlink():
        ordinary(path)
    if '\n' in path.name or '\r' in path.name or path == bundle:
        raise ValueError('Unsafe supplement output path.')
    return path


def pack_artwork(wanted, output, *, barn_root=BARN_ROOT, expected_bundle_sha256=EXPECTED_SHA256):
    barn_root = ordinary(barn_root, directory=True)
    # Validate the entire request before opening any of the local image copies.
    selected = bundle_artwork(barn_root, expected_bundle_sha256)
    records = validate_wanted(wanted, selected, expected_bundle_sha256)
    bundle = barn_root / '.build' / BUNDLE_NAME
    output = output_path(output, bundle)
    checksum_path = output_path(Path(str(output) + '.sha256'), bundle)
    source_directory = barn_root / 'static' / 'assets' / 'items'
    if output.is_relative_to(source_directory) or checksum_path.is_relative_to(source_directory):
        raise ValueError('The supplement output would overwrite an artwork source.')
    temporary = checksum_temporary = None
    total = 0
    try:
        descriptor, temporary = tempfile.mkstemp(prefix='.barn-artwork-', dir=output.parent)
        with os.fdopen(descriptor, 'wb') as raw:
            with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0) as compressed:
                with tarfile.open(fileobj=compressed, mode='w|', format=tarfile.USTAR_FORMAT) as archive:
                    for index, record in enumerate(records, 1):
                        source = barn_root / record['path']
                        contents = read_regular(source, record['bytes'])
                        if len(contents) != record['bytes'] or digest(contents) != record['sha256']:
                            raise ValueError('Local Barn artwork does not match the reviewed catalog: ' + record['path'])
                        member = tarfile.TarInfo('GodBarn/' + record['path'])
                        member.size = len(contents)
                        member.mode = 0o644
                        member.uid = member.gid = member.mtime = 0
                        member.uname = member.gname = ''
                        archive.addfile(member, io.BytesIO(contents))
                        total += len(contents)
                        if index % 1000 == 0:
                            progress(f'Packed {index:,} of {len(records):,} verified missing images.')
            raw.flush()
            os.fsync(raw.fileno())
        archive_sha = hashlib.sha256()
        with open(temporary, 'rb') as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b''):
                archive_sha.update(chunk)
        archive_sha = archive_sha.hexdigest()
        descriptor, checksum_temporary = tempfile.mkstemp(prefix='.barn-artwork-sha-', dir=output.parent)
        with os.fdopen(descriptor, 'w', encoding='ascii') as stream:
            stream.write(archive_sha + '  ' + output.name + '\n')
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, output)
        temporary = None
        os.replace(checksum_temporary, checksum_path)
        checksum_temporary = None
    finally:
        for path in (temporary, checksum_temporary):
            if path is not None:
                Path(path).unlink(missing_ok=True)
    result = {'items': len(records), 'bytes': total, 'sha256': archive_sha, 'archive': str(output)}
    progress(f'Prepared {len(records):,} verified missing images ({total:,} bytes).')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--wanted', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    arguments = parser.parse_args()
    try:
        wanted = json_without_duplicate_keys(read_regular(arguments.wanted, MAX_REQUEST_BYTES))
        result = pack_artwork(wanted, arguments.output)
    except (OSError, ValueError, tarfile.TarError, EOFError) as error:
        print('[God Barn artwork] Packing stopped: ' + str(error), file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == '__main__':
    sys.exit(main())
